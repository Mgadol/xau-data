import numpy as np
import pandas as pd
from core import load

d5 = load('XAU_5m_data.csv', start='2005-01-01', end='2025-09-12')
_M = d5.index.hour * 60 + d5.index.minute
DF = pd.DataFrame({'day': d5.index.normalize(), 'm': _M,
                   'o': d5['open'].values, 'h': d5['high'].values,
                   'l': d5['low'].values, 'c': d5['close'].values})

ASIA = (0, 8 * 60)
LON = (8 * 60, 16 * 60)
NY = (16 * 60, 23 * 60)


def build():
    """Өдөр бүрд Азийн муж, Лондоны хамалт, NY-гийн өгөөжийг гаргана."""
    rows = []
    prev_hi = prev_lo = None
    for day, g in DF.groupby('day', sort=True):
        m = g['m'].values
        H, L, C, O = g['h'].values, g['l'].values, g['c'].values, g['o'].values
        a = (m >= ASIA[0]) & (m < ASIA[1])
        l_ = (m >= LON[0]) & (m < LON[1])
        n_ = (m >= NY[0]) & (m < NY[1])
        d_hi, d_lo = H.max(), L.min()
        if a.sum() < 12 or l_.sum() < 12 or n_.sum() < 12:
            prev_hi, prev_lo = d_hi, d_lo
            continue

        a_hi, a_lo = H[a].max(), L[a].min()
        lH, lL, lC = H[l_], L[l_], C[l_]
        took_hi = lH.max() > a_hi
        took_lo = lL.min() < a_lo
        # ХЭЗЭЭ хамсан бэ — хоёуланг нь хамсан үед аль нь сүүлд вэ
        i_hi = int(np.argmax(lH > a_hi)) if took_hi else 10 ** 9
        i_lo = int(np.argmax(lL < a_lo)) if took_lo else 10 ** 9
        lon_c = lC[-1]

        rows.append(dict(
            day=day, a_hi=a_hi, a_lo=a_lo, a_rng=a_hi - a_lo,
            took_hi=took_hi, took_lo=took_lo,
            last_hi=(i_hi > i_lo),          # хоёуланг нь хамсан бол: дээд нь сүүлд
            lon_c=lon_c,
            close_above=lon_c > a_hi, close_below=lon_c < a_lo,
            ny_o=O[n_][0], ny_c=C[n_][-1],
            p_hi=prev_hi, p_lo=prev_lo,
            lon_hi=lH.max(), lon_lo=lL.min(),
            year=day.year))
        prev_hi, prev_lo = d_hi, d_lo

    T = pd.DataFrame(rows).set_index('day')
    tr = np.maximum(T['lon_hi'] - T['lon_lo'], T['a_rng'])
    T['atr'] = tr.rolling(14).mean()
    T = T[T['atr'] > 0].dropna(subset=['atr'])
    T['ny'] = (T['ny_c'] - T['ny_o']) / T['atr']       # ATR-ээр
    T['ny_usd'] = T['ny_c'] - T['ny_o']
    return T


T = build()


def case(t):
    """Нэг өдрийг зургаан нөхцлийн аль нэгэнд хуваарилна."""
    if t['took_hi'] and t['took_lo']:
        return '5b' if t['last_hi'] else '5a'
    if t['took_hi']:
        return '1' if t['close_above'] else '2'
    if t['took_lo']:
        return '3' if t['close_below'] else '4'
    return '0'


T['case'] = T.apply(case, axis=1)

LABEL = {
    '0':  'аль нь ч хамаагүй',
    '1':  'ДЭЭД хамж · дээр хаагдсан',
    '2':  'ДЭЭД хамж · БУЦАЖ хаагдсан',
    '3':  'ДООД хамж · доор хаагдсан',
    '4':  'ДООД хамж · БУЦАЖ хаагдсан',
    '5a': 'ХОЁУЛАНГ · ДООД нь сүүлд',
    '5b': 'ХОЁУЛАНГ · ДЭЭД нь сүүлд',
}
ORDER = ['0', '1', '2', '3', '4', '5a', '5b']


def line(s, lbl, base=None):
    """Нэг бүлгийн NY өгөөж ба өсөх магадлал."""
    if len(s) < 25:
        print(f"   {lbl:<32}{len(s):>6}   (цөөн)")
        return
    ny = s['ny']
    se = ny.std() / np.sqrt(len(ny))
    up = (s['ny_usd'] > 0).mean() * 100
    mark = '  ✓' if abs(ny.mean()) > 2 * se else '  ✗'
    rel = ''
    if base is not None:
        rel = f"  ({ny.mean() - base:+.3f} суурьаас)"
    print(f"   {lbl:<32}{len(s):>6} {up:>6.1f}% {ny.mean():>+8.3f} ±{se:.3f}{mark}{rel}")


if __name__ == '__main__':
    print("Лондон Азийн мужийн аль талыг хамсан бэ → NY хаашаа явав\n")
    print("«өсөв %» = NY өссөн өдрийн хувь")
    print("«NY»     = NY сессийн өгөөж, ATR-ээр (+ өсөв, − унав)\n")

    base = T['ny'].mean()
