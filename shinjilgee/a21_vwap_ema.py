import numpy as np
import pandas as pd
from core import load, resample

H1 = load(start='2005-01-01', end='2025-09-12')
D5 = load('XAU_5m_data.csv', start='2005-01-01', end='2025-09-12')


def frame(tf):
    """Хугацааны хүрээ бэлдэнэ. 5м-ээс бусад нь 1ц-аас гарна."""
    if tf == '5m':
        return D5.copy()
    if tf == '1h':
        return H1.copy()
    return resample(H1, tf)


def signals(d, ema_n):
    """VWAP (өдрөөр дахин тоолно) ба EMA. Байрлалыг буцаана.

    Байрлал: хоёулангаас дээш → +1, хоёулангаас доош → −1,
    дундуур бол ӨМНӨХИЙГ барина (зурган дээрх дүрэм).
    """
    c = d['close']
    tp = (d['high'] + d['low'] + d['close']) / 3      # ердийн үнэ
    v = d['volume'].replace(0, np.nan).fillna(1.0)
    day = d.index.normalize()
    cum_pv = (tp * v).groupby(day).cumsum()
    cum_v = v.groupby(day).cumsum()
    vwap = cum_pv / cum_v
    ema = c.ewm(span=ema_n, adjust=False).mean()

    up = (c > vwap) & (c > ema)
    dn = (c < vwap) & (c < ema)
    pos = pd.Series(np.where(dn, -1.0, np.where(up, 1.0, np.nan)), index=d.index)
    return pos.ffill().fillna(0.0), vwap, ema


def run(tf='1h', ema_n=20, spread=0.3, side=None, years=None):
    """Буцаах: dict — нийт $, арилжааны тоо, ялалт, дундаж."""
    d = frame(tf)
    pos, _, _ = signals(d, ema_n)
    if side == 'urt':
        pos = pos.clip(lower=0)
    elif side == 'bogino':
        pos = pos.clip(upper=0)

    c = d['close']
    if years:
        m = (d.index.year >= years[0]) & (d.index.year < years[1])
        d, pos, c = d[m], pos[m], c[m]

    # Байрлал i-р барын хаалтад тогтоогдож, i+1 хүртэл барина
    ret = pos.shift(1).fillna(0) * c.diff()
    flips = pos.diff().abs().fillna(0)
    cost = flips * spread                    # солигдох бүрд спред
    net = ret - cost

    # ── Арилжаа тус бүрээр ──
    # АНХААР: зардлыг байрлал СОЛИГДСОН бар дээр төлдөг тул түүнийг
    # ДУУССАН арилжаанд онооно. Урьд нь шинэ (эсвэл хоосон) бүлэгт
    # ороод, side='urt' үед «дундаж +3.62$, нийт −811$» гэсэн
    # зөрчилтэй тоо гаргаж байв.
    pv = pos.values
    cv = c.values
    trades = []
    i = 0
    n_ = len(pv)
    while i < n_:
        j = i
        while j + 1 < n_ and pv[j + 1] == pv[i]:
            j += 1
        # АНХААР: `j > i` гэж шүүвэл НЭГ БАРЫН арилжаанууд хасагдана.
        # Тэдгээр нь голдуу хамгийн муу нь (whipsaw) тул дундаж хиймлээр
        # өснө. Урьд нь «дундаж +0.44$, нийт −4821$» гэсэн зөрчил
        # яг эндээс гарч байв.
        if pv[i] != 0:
            k = min(j + 1, n_ - 1)
            pnl = pv[i] * (cv[k] - cv[i]) - abs(pv[i]) * spread * 2
            trades.append(pnl)
        i = j + 1
    grp = pd.Series(trades, dtype=float)

    hold = float(c.iloc[-1] - c.iloc[0])
    return dict(
        n=int(len(grp)), total=float(net.sum()), hold=hold,
        win=float((grp > 0).mean() * 100) if len(grp) else np.nan,
        avg=float(grp.mean()) if len(grp) else np.nan,
        se=float(grp.std() / np.sqrt(len(grp))) if len(grp) > 1 else np.nan,
        flips=int(flips.sum() / 2))


def line(lbl, r):
    if r['n'] < 25:
        return f"   {lbl:<26}{r['n']:>7}  (цөөн)"
    ok = '  ✓' if r['avg'] > 2 * r['se'] else ''
    return (f"   {lbl:<26}{r['n']:>7}{r['win']:>7.1f}%"
            f"{r['avg']:>+9.2f}${r['se']:>7.2f}"
            f"{r['total']:>+11.0f}${ok}")


