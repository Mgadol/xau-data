import numpy as np
import pandas as pd
from core import load

h = load(start='2005-01-01', end='2025-09-12')


def series(rule):
    """Хаалтын цувааг өгсөн хүрээнд гаргана."""
    c = h['close'].resample(rule).last().dropna()
    return c


def tstat(x):
    x = np.asarray(x, float)
    x = x[~np.isnan(x)]
    if len(x) < 10:
        return np.nan, np.nan, len(x)
    se = x.std(ddof=1) / np.sqrt(len(x))
    return x.mean(), x.mean() / se if se > 0 else np.nan, len(x)


def momentum(c, L, H, cost_pa=0.0, both=True):
    """L үеийн момент → дараагийн H үеийн байрлал.

    Дохио нь t үеийн ХААЛТААР мэдэгдэнэ → t..t+H үеийн өгөөжийг
    авна. Давхцуулахгүйн тулд H алхмаар үсэрнэ (алдааг зөв тооцно).
    """
    lr = np.log(c).diff()
    n = len(c)
    per_year = {'1D': 252, '1W': 52, 'ME': 12}
    out = {'mom': [], 'hold': [], 'sig': []}
    i = L
    while i + H < n:
        past = lr.iloc[i - L + 1:i + 1].sum()
        fwd = lr.iloc[i + 1:i + H + 1].sum()
        s = 1 if past > 0 else (-1 if both else 0)
        out['mom'].append(s * fwd)
        out['hold'].append(fwd)
        out['sig'].append(s)
        i += H
    return (np.array(out['mom']), np.array(out['hold']),
            np.array(out['sig']))


def grid(rule, name, LS, HS, both=True):
    c = series(rule)
    print(f"\n   ══ {name} ══   ({len(c):,} үе)")
    print(f"   {'эргэх':<7}{'барих':<7}{'n':>5}{'момент':>9}{'үргэлж':>9}"
          f"{'ЗӨРҮҮ':>9}{'t':>6}{'зөв%':>7}{'суурь':>7}{'илүү':>7}")
    print("   " + "─" * 72)
    for L in LS:
        for H in HS:
            m, b, s = momentum(c, L, H, both=both)
            if len(m) < 10:
                continue
            d = m - b
            md, td, n = tstat(d)
            # НАРИЙВЧЛАЛЫГ ДАНГААР НЬ БҮҮ ХАР. «65% зөв» гэдэг нь алт
            # тэр хугацаанд 72% дээш явсан бол МУУ гэсэн үг.
            hit = (np.sign(s) == np.sign(b)).mean() * 100
            base = (b > 0).mean() * 100
            mark = '  ←' if abs(td) >= 2 else ''
            print(f"   {L:<7}{H:<7}{n:>5}{m.mean() * 100:>8.2f}%"
                  f"{b.mean() * 100:>8.2f}%{md * 100:>+8.2f}%{td:>6.2f}"
                  f"{hit:>6.1f}%{base:>6.1f}%{hit - base:>+7.1f}{mark}")


def split_check(rule, L, H, name):
    """Урт/богино, хугацааны хуваалт — нэг тохиргоон дээр гүнзгий."""
    c = series(rule)
    lr = np.log(c).diff()
    n = len(c)
    rows = []
    i = L
    while i + H < n:
        past = lr.iloc[i - L + 1:i + 1].sum()
        fwd = lr.iloc[i + 1:i + H + 1].sum()
        rows.append((c.index[i], 1 if past > 0 else -1, fwd))
        i += H
    R = pd.DataFrame(rows, columns=['dt', 'sig', 'fwd']).set_index('dt')
    R['mom'] = R['sig'] * R['fwd']
    print(f"\n   ── {name}: эргэх {L}, барих {H} ──")
    for lbl, sub in (('бүгд', R),
                     ('зөвхөн УРТ дохио', R[R['sig'] > 0]),
                     ('зөвхөн БОГИНО дохио', R[R['sig'] < 0]),
                     ('2005–2016', R[R.index.year < 2017]),
                     ('2017–2025', R[R.index.year >= 2017])):
        if len(sub) < 10:
            print(f"      {lbl:<22}{len(sub):>5}  (цөөн)")
            continue
        d = sub['mom'] - sub['fwd']
        md, td, nn = tstat(d)
        mk = ' ✓' if abs(td) >= 2 else ' ✗'
        print(f"      {lbl:<22}{nn:>5}   момент {sub['mom'].mean() * 100:>+6.2f}%"
              f"   үргэлж {sub['fwd'].mean() * 100:>+6.2f}%"
              f"   зөрүү {md * 100:>+6.2f}%  t={td:>5.2f}{mk}")


def long_only(rule, L, H, name, swap_pa=0.03):
    """Богино талыг ХАСАЖ, зөвхөн «байх/байхгүй» гэж шалгана.

    Спот алтан дээр богино барихад хүүгийн зөрүү нь ЭСРЭГЭЭРЭЭ
    ажилладаг ба олон брокер хязгаартай. Практикт хамгийн бодит
    хувилбар нь: момент эерэг бол бай, сөрөг бол БЭЛЭН МӨНГӨ.
    """
    c = series(rule)
    lr = np.log(c).diff()
    per = {'1D': 252, '1W': 52, 'ME': 12}[rule]
    n = len(c)
    mom, hold, inmkt = [], [], []
    i = L
    while i + H < n:
        past = lr.iloc[i - L + 1:i + 1].sum()
        fwd = lr.iloc[i + 1:i + H + 1].sum()
        s = 1 if past > 0 else 0
        mom.append(s * fwd)
        hold.append(fwd)
        inmkt.append(s)
        i += H
    mom, hold, inmkt = np.array(mom), np.array(hold), np.array(inmkt)
    sw = swap_pa * H / per                     # зөвхөн зах зээлд байхад
    momc = mom - inmkt * sw
    holdc = hold - sw
    d = momc - holdc
    md, td, nn = tstat(d)
    print(f"\n   ── {name} УРТ ЭСВЭЛ БЭЛЭН (своп {swap_pa * 100:.0f}%/жил) ──")
    print(f"      эргэх {L}, барих {H},  n={nn},  зах зээлд "
          f"{inmkt.mean() * 100:.0f}% хугацаанд")
    print(f"      момент  {momc.mean() * 100:+6.2f}% / үе    "
          f"хуримтлал {np.exp(momc.sum()) - 1:>8.1%}")
    print(f"      үргэлж  {holdc.mean() * 100:+6.2f}% / үе    "
          f"хуримтлал {np.exp(holdc.sum()) - 1:>8.1%}")
    print(f"      ЗӨРҮҮ   {md * 100:+6.2f}% / үе    t={td:.2f}"
          f"{'  ✓' if abs(td) >= 2 else '  ✗'}")
    sm = momc.std(ddof=1)
    sh = holdc.std(ddof=1)
    print(f"      хэлбэлзэл  момент {sm * 100:.2f}%   үргэлж {sh * 100:.2f}%"
          f"   →  Шарп {momc.mean() / sm * np.sqrt(per / H):.2f} vs "
          f"{holdc.mean() / sh * np.sqrt(per / H):.2f}")
    # хамгийн муу уналт
    for lbl, x in (('момент', momc), ('үргэлж', holdc)):
        eq = np.exp(np.cumsum(x))
        dd = (eq / np.maximum.accumulate(eq) - 1).min()
        print(f"      хамгийн муу уналт ({lbl}): {dd:.1%}")


