import numpy as np
import pandas as pd
from a15_medee import D

DD = D.groupby('day').agg(dow=('dow', 'first'), dom=('dom', 'first'),
                          o=('o', 'first'), c=('c', 'last'),
                          hi=('h', 'max'), lo=('l', 'min'))
DD['span'] = DD['hi'] - DD['lo']
DD = DD[DD['span'] > DD['span'].median() * 0.1]
DD['usd'] = DD['c'] - DD['o']
DD['year'] = DD.index.year
FRI = D[D['dow'] == 4].copy()
FRI['hr'] = FRI['m'] // 60


def window(a, b, sp=0.3, days=FRI):
    """Цонх доторх нээлт→хаалт өгөөж, спред хассан."""
    s = days[(days['m'] >= a) & (days['m'] < b)].groupby('day').agg(
        o=('o', 'first'), c=('c', 'last'))
    return (s['c'] - s['o']) - sp


def rep(r, lbl):
    se = r.std() / np.sqrt(len(r))
    yr = r.groupby(r.index.year).mean()
    print(f"   {lbl:<30}n={len(r):>4} {r.mean():>+8.3f}$ ±{se:.3f} "
          f"ялалт {(r > 0).mean() * 100:>4.1f}%  {(yr > 0).sum()}/{len(yr)} жил"
          f"{'  ✓' if r.mean() > 2 * se else '  ✗'}")


if __name__ == '__main__':
    NM = ['Даваа', 'Мягмар', 'Лхагва', 'Пүрэв', 'Баасан']
    print("Баасан гарагийн нөлөө — эцсийн шалгалт\n")

    print("── 1. Гараг бүрээр (нээлт→хаалт, $, зардалгүй) ──\n")
    print(f"   {'гараг':<10}{'n':>6}{'дундаж':>10}{'±SE':>8}"
          f"{'2005–2016':>12}{'2017–2025':>12}")
    print("   " + "─" * 60)
    for k in range(5):
        s = DD[DD['dow'] == k]
        se = s['usd'].std() / np.sqrt(len(s))
        print(f"   {NM[k]:<10}{len(s):>6}{s['usd'].mean():>+10.3f}{se:>8.3f}"
              f"{s[s['year'] < 2017]['usd'].mean():>+12.3f}"
              f"{s[s['year'] >= 2017]['usd'].mean():>+12.3f}")

    F = DD[DD['dow'] == 4]
    print("\n\n── 2. Баасан — гажуудлын шалгалт ──\n")
    print(f"   дундаж   {F['usd'].mean():>+7.3f}")
    print(f"   МЕДИАН   {F['usd'].median():>+7.3f}   "
          f"(дундажтай ойролцоо → цөөн өдөр үүрээгүй)")
    tr = F['usd'].clip(F['usd'].quantile(.02), F['usd'].quantile(.98))
    print(f"   тайрсан  {tr.mean():>+7.3f}   (захын 2% хассан)")
    print()
    for m, lbl in ((F['dom'] <= 7, 'NFP-ийн Баасан'),
                   (F['dom'] > 7, 'бусад Баасан')):
        s = F[m]['usd']
        se = s.std() / np.sqrt(len(s))
        print(f"   {lbl:<24}n={len(s):>4}  {s.mean():>+7.3f} ±{se:.3f}"
              f"{'  ✓' if s.mean() > 2 * se else '  ✗'}")

    print("\n   Жил бүрээр:")
    g = F.groupby('year')['usd'].mean()
    for y, x in g.items():
        bar = '█' * max(0, int(x * 2)) if x > 0 else '░' * max(0, int(-x * 2))
        print(f"      {y}  {x:>+6.2f}  {bar}")
    print(f"      → {(g > 0).sum()}/{len(g)} жил эерэг")

    print("\n\n── 3. ГҮЙЦЭТГЭХ БОЛОМЖТОЙ ЮУ (спред $0.3) ──")
    print("   Бүтэн өдөр ажиллаж байхад хэсэг нь ажиллах ёстой.\n")
    rep(window(0, 24 * 60), 'бүтэн өдөр 00:00–23:55')
    rep(window(0, 8 * 60), 'Ази 00:00–08:00')
    rep(window(16 * 60, 24 * 60), 'NY 16:00–23:55')
    rep(window(16 * 60, 21 * 60), 'NY хөрвөх 16:00–21:00')
    rep(window(8 * 60, 21 * 60), 'Лондон+NY 08:00–21:00')
    print("\n   Ямар ч ХӨРВӨХ ЧАДВАРТАЙ цонх давж гарахгүй байна.")

    print("\n\n── 4. ХААНА төвлөрснийг цаг тутмаар олъё ──")
    print("   «хөрвөх» = тухайн цагийн дундаж муж / өдрийн дундаж.\n")
    print(f"   {'брокер':<8}{'УБ':<8}{'өгөөж $':>10}{'±SE':>8}{'хөрвөх':>9}")
    print("   " + "─" * 46)
    tot = 0.0
    thin = 0.0
    for h, gg in FRI.groupby('hr'):
        s = gg.groupby('day').agg(o=('o', 'first'), c=('c', 'last'))
        r = s['c'] - s['o']
        se = r.std() / np.sqrt(len(r))
        liq = gg['norm'].mean()
        tot += r.mean()
        if h >= 21:
            thin += r.mean()
        print(f"   {h:02d}:00   {(h + 5) % 24:02d}:00  {r.mean():>+9.3f}"
              f"{se:>8.3f}{liq:>8.2f}×"
              f"{'  ✓' if abs(r.mean()) > 2 * se else '   '}"
              f"{'  ← НИМГЭН' if liq < 0.75 else ''}")
    print(f"\n   Нийт {tot:+.3f}$   |   сүүлийн 3 цаг (21–24) {thin:+.3f}$ "
          f"= {thin / tot * 100:.0f}%")
    print("   Нөлөөний гуравны хоёр нь долоо хоногийн хаалтын өмнөх")
    print("   хамгийн нимгэн цагт байна. Тэнд спред $0.3 биш, $1–5.")

    print("\n\n── 5. Спред бодитой болговол ──\n")
    for sp in (0.3, 0.5, 0.8, 1.5):
        rep(window(0, 24 * 60, sp), f'бүтэн өдөр · спред ${sp}')

    print("\n   ДҮГНЭЛТ: нөлөө нь ЖИНХЭНЭ байж болох ч гүйцэтгэх")
    print("   боломжгүй. Ашиг нь арилжаалж чадахгүй цагт л байна.")
