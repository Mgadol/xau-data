"""4. Хөрвөх чадварын цэвэрлэгээ (liquidity sweep) — SMC-ийн суурь механизм.

Санаа:
  Дээд хугацаанд хэлбэлзлийн оргил/ёроол байна — тэнд стопууд хуримтлагдана.
  Үнэ түүнийг давж ЦЭВЭРЛЭЭД, эргээд дотогшоо хаагдвал өдөөлт байсан
  гэсэн үг, эсрэг чигт эргэнэ гэж үздэг.

Энд ЯГ ҮҮНИЙГ л хэмжинэ — CHoCH, IDM, шахалтын нарийн тодорхойлолтгүйгээр.
Суурь нь ажиллахгүй бол дээр нь босгосон бүтэц ч ажиллахгүй.

  Цэвэрлэгээ : 5м үнэ дээд хугацааны пивотыг ДАВНА
  Дохио      : 5м лаа тэр түвшнээс буцаж ДОТОГШОО хаагдана
  Оролт      : тэр лааны хаалт
  Стоп       : цэвэрлэгээний хамгийн алсын цэг
  Target     : 1:2

ДӨРВӨН ШАЛГУУР (гол нь энэ — дундаж эерэг байх нь хангалтгүй):
  1. Урт/богино тэгш хэм. Зөвхөн нэг тал нь ажиллаж байвал энэ нь
     аргачлал биш, алтны өсөх хандлага (drift) юм.
  2. Хугацааны хуваалт. 2005–2016 / 2017–2025 хоёуланд нь давтагдах ёстой.
  3. Спред. $0.3 нэмэхэд амьд үлдэх ёстой.
  4. Стопын зай. Спредээс нарийн стоптой арилжаа бодит биш — тэдгээр нь
     үр дүнг татаж байгаа эсэхийг шалгана.

ҮР ДҮН: ДАВУУ ТАЛГҮЙ.

      4ц · ZigZag 1%   2026 арилжаа   32.5%   −0.066R ±0.030
      зөвхөн урт        977           33.7%   −0.040R
      зөвхөн богино    1049           31.4%   −0.090R
      2005–2016        1365           33.6%   −0.036R
      2017–2025         511           30.5%   −0.116R

  Спредгүй байсан ч ердөө +0.055R ±0.031 — өөрөөр хэлбэл суурь механизм
  өөрөө бараг тэг, зардал нь түүнийг сөрөг болгож байна.

  Гүн цэвэрлэгээ (≥3 ATR) нь хамгийн сайн нь: +0.079R ±0.068. Гэхдээ
  энэ нь ч гэсэн тэгээс ялгарахгүй. Гүн 1 → 2 → 3 ATR болох тусам үр
  дүн жигд сайжирна (−0.020 → +0.021 → +0.079), тиймээс гүн гэдэг нь
  МЭДЭЭЛЭЛ агуулж байна — харин арилжаа хийхэд хангалттай биш.
  Ашиглах гэвэл: гүехэн цэвэрлэгээг ОРХИХ шүүлтүүр болгоно, дохио биш.

ЭНЭ ФАЙЛ ЯАЖ НЭГ УДАА ХУДАЛ ХАРИУ ӨГСӨН БЭ
  Анх энэ бүх тоо ГЯЛАЛЗАЖ байсан: гүн ≥3 ATR нь +0.381R, хоёр хугацаанд
  ЯГ ижил, урт богино хоёулаа — дөрвөн шалгуурыг бүгдийг нь давсан.
  Тэр нь худал байв.

  Шалтгаан: 5 минутын хайлтыг баталгааны 4 цагийн бар НЭЭГДЭХ мөчөөс
  эхлүүлж байсан. Гэтэл баталгаа нь тэр бар ХААГДАХАД л мэдэгддэг.
  Улмаас эхний 48 ширхэг 5м бар нь ирээдүйн мэдээлэл ашигласан.
  Нэг мөр залруулахад (core.bar_len) +0.381R → +0.079R болов.

  Сургамж: тоо хэт сайхан байвал эхлээд алдаагаа хай. Ялангуяа хоёр
  өөр хугацааны хүрээ холилдож байгаа газар.
"""
import numpy as np
import pandas as pd
from core import load, resample, zigzag, confirm_index, stat, bar_len

h = load(start='2005-01-01', end='2025-09-12')
D5 = load('XAU_5m_data.csv', start='2005-01-01', end='2025-09-12')

H, L, C = D5['high'].values, D5['low'].values, D5['close'].values
IDX = D5.index

_tr = np.maximum(H[1:] - L[1:], np.maximum(abs(H[1:] - C[:-1]), abs(L[1:] - C[:-1])))
ATR20 = pd.Series(np.concatenate([[H[0] - L[0]], _tr])).rolling(20).mean().values


def levels(tf, pct):
    """Дээд хугацааны пивотууд — БАТЛАГДСАН цагийн хамт.

    Батлагдсан цагийг авах нь чухал. Пивот үүссэн даруйдаа мэдэгддэггүй
    тул үүссэн цагаас нь тоолвол ирээдүй харсан болно.

    Мөн баталгааны бар НЭЭГДЭХ биш ХААГДАХ мөчийг авна — bar_len()-ийг
    үзнэ үү. Энэ ялгааг алдсанаас болж худал олдвор гарч байсан.
    """
    d = resample(h, tf)
    dt = bar_len(tf)
    out = []
    for (pi, pv, pdir) in zigzag(d, pct):
        ci = confirm_index(d, pi, pv, pdir, pct)
        if ci is not None:
            out.append((d.index[ci] + dt, pv, pdir))
    return out


def run(tf='4h', pct=0.01, rr=2.0, maxbars=288, spread=0.3,
        side=None, min_depth=None, years=None, min_risk=None, ret_risk=False):
    """Нэг тохиргоогоор бүх цэвэрлэгээг туулж R-ийн жагсаалт буцаана.

    side      : 'urt' | 'bogino' | None (хоёулаа)
    min_depth : түвшнээс хэдэн ATR доош/дээш давсан байхыг шаардах
    years     : (эхлэх, дуусах) он — хугацааны хуваалтад
    min_risk  : стопын зай ($) хамгийн багадаа. Үүнээс нарийн стоп нь
                спредээс жижиг тул бодит амьдрал дээр арилжигдахгүй.
    ret_risk  : R-ийн оронд (R, стопын зай) буцаана
    """
    res = []
    for t0, px, pdir in levels(tf, pct):
        if years and not (years[0] <= t0.year < years[1]):
            continue
        s = IDX.searchsorted(t0)
        if s < 200 or s >= len(IDX) - maxbars:
            continue
        short = (pdir == 1)          # оргилыг цэвэрлэвэл богино
        if side == 'urt' and short:
            continue
        if side == 'bogino' and not short:
            continue

        far = px                     # цэвэрлэгээний хамгийн алсын цэг
        hit = False
        for i in range(s, s + maxbars):
            breached = H[i] > px if short else L[i] < px
            if not breached:
                continue
            hit = True
            far = max(far, H[i]) if short else min(far, L[i])
            inside = C[i] < px if short else C[i] > px
            if not inside:
                continue

            a = ATR20[i]
            if min_depth is not None:
                if not (a > 0) or abs(far - px) / a < min_depth:
                    break        # гүехэн — энэ түвшнийг бүхэлд нь орхино
            e = C[i] - spread if short else C[i] + spread
            st = far
            if (st - e if short else e - st) <= 0:
                break
            risk = abs(st - e)
            if min_risk is not None and risk < min_risk:
                break
            tg = e - rr * risk if short else e + rr * risk
            r = None
            for j in range(i + 1, min(i + maxbars, len(IDX))):
                if short:
                    if H[j] >= st: r = -1.0; break
                    if L[j] <= tg: r = rr;   break
                else:
                    if L[j] <= st: r = -1.0; break
                    if H[j] >= tg: r = rr;   break
            if r is None:
                # Дуусаагүй арилжааг ХАЯХГҮЙ — зах зээлийн үнээр хаана.
                # Хаявал алдагдалтай нь голдуу унаж, хиймэл сайхан гардаг.
                px_end = C[min(i + maxbars, len(IDX)) - 1]
                r = ((e - px_end) if short else (px_end - e)) / risk
            res.append((r, risk) if ret_risk else r)
            break
    return np.array(res)


if __name__ == '__main__':
    print("Хөрвөх чадварын цэвэрлэгээ → эргэлт.  5м гүйцэтгэл, TP 1:2\n")

    print("── 1. Дээд хугацаа бүрээр (спред $0.3) ──\n")
    print(f"   {'':<30}{'n':>6} {'Ялалт':>7} {'Дундаж':>9}")
    print("   " + "─" * 62)
    for tf, pct in (('4h', 0.01), ('4h', 0.02), ('1D', 0.02), ('1D', 0.03), ('1W', 0.03)):
        print("   " + stat(run(tf, pct), f"{tf} · ZigZag {pct * 100:.0f}%"))

    print("\n── 2. Спредгүй байсан бол (зардлын нөлөө) ──\n")
    for tf, pct in (('4h', 0.01), ('1D', 0.02)):
        print("   " + stat(run(tf, pct, spread=0.0), f"{tf} · ZigZag {pct * 100:.0f}% · спредгүй"))

    print("\n── 3. Урт/богино тэгш хэм (4ц 1%) ──")
    print("   Зөвхөн урт нь ажиллаж байвал энэ нь алтны өсөх хандлага.\n")
    for side, lbl in ((None, 'хоёулаа'), ('urt', 'зөвхөн УРТ'), ('bogino', 'зөвхөн БОГИНО')):
        print("   " + stat(run('4h', 0.01, side=side), lbl))

    print("\n── 4. Хугацааны хуваалт (4ц 1%) ──\n")
    for yrs, lbl in (((2005, 2015), '2005–2014'), ((2015, 2026), '2015–2025'),
                     ((2017, 2026), '2017–2025')):
        print("   " + stat(run('4h', 0.01, years=yrs), lbl))

    print("\n── 5. Стопын зай (спредээс нарийн стоп үр дүнг гажуудуулж байна уу) ──\n")
    for mr, lbl in ((None, 'бүгд'), (1.0, 'стоп ≥ $1'), (2.0, 'стоп ≥ $2'), (3.0, 'стоп ≥ $3')):
        print("   " + stat(run('4h', 0.01, min_risk=mr), lbl))
    print("\n   Нарийн стоптой нь ХАМГИЙН МУУ тул үр дүн тэднээс гараагүй.")

    print("\n── 6. Цэвэрлэгээний ГҮН (4ц 1%, спред $0.3) ──")
    print("   Түвшнээс хэр гүн давсан бэ. Гүн нь жинхэнэ стоп цэвэрлэгээ,")
    print("   гүехэн нь ердөө шуугиан.\n")
    for md, lbl in ((None, 'бүгд'), (1.0, 'гүн ≥ 1 ATR'),
                    (2.0, 'гүн ≥ 2 ATR'), (3.0, 'гүн ≥ 3 ATR')):
        print("   " + stat(run('4h', 0.01, min_depth=md), lbl))

    print("\n── 7. Гүн ≥3 ATR-ийг дөрвөн шалгуураар ──")
    print("   Энэ хэсэг л шийднэ. Аль нэг мөр нь унавал олдвор биш.\n")
    for kw, lbl in ((dict(years=(2005, 2017)), '2005–2016'),
                    (dict(years=(2017, 2026)), '2017–2025'),
                    (dict(side='urt'), 'зөвхөн УРТ'),
                    (dict(side='bogino'), 'зөвхөн БОГИНО'),
                    (dict(spread=0.6), 'спред $0.6 (2 дахин)')):
        print("   " + stat(run('4h', 0.01, min_depth=3.0, **kw), lbl))
